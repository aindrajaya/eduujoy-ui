// Eduujoy Sketch design tokens (PRD-UI §4b) to CSS. Reads src/ui/sketch/tokens.json, a byte-for-byte
// copy of ../docs/design-system/tokens.json, so builds never read outside ui/. Writes:
// - src/ui/sketch/tokens.css: --sk-* custom properties (light under :root, dark
//   under [data-theme="dark"], and under prefers-color-scheme: dark when no theme is set);
// - src/ui/sketch/fonts.css: the @font-face rules (font-display: swap). Screens load it after first
//   paint: font requests before the first paint put both fonts on /demo's LCP path (+0.45 s measured).
// - src/ui/sketch/theme.css: the Tailwind theme mapping (bg-sk-surface, rounded-sk-wobble-card, ...).
// `--check` regenerates in memory and fails when a token has no variable, a generated file is stale,
// or a contrast pair from the design-system README misses its floor in either theme.
import { readFileSync, writeFileSync } from 'node:fs';

const DIR = 'src/ui/sketch';
const HEADER = '/* Generated by scripts/sketch-tokens.mjs from tokens.json; do not edit. Run `pnpm tokens`. */\n';
const tokens = JSON.parse(readFileSync(`${DIR}/tokens.json`, 'utf8'));
const THEMES = tokens.color.themes.map((t) => t.id);

const textStyles = tokens.type.groups.flatMap((g) => g.styles.map((s) => ({ ...s, family: g.family })));
const flat = (group) => group.tokens.map((t) => [t.name, t.value]);
const fixed = [...flat(tokens.spacing), ...flat(tokens.radius), ...flat(tokens.wobble), ...flat(tokens.stroke)];

/** Every variable a token needs, by theme ('all' for theme-independent values). */
function variables() {
  const vars = { all: [], light: [], dark: [] };
  for (const [family, stack] of Object.entries(tokens.type.families)) vars.all.push([`font-${family}`, stack]);
  for (const s of textStyles) {
    vars.all.push([`${s.name}-size`, s.fontSize], [`${s.name}-line-height`, String(s.lineHeight)], [`${s.name}-weight`, String(s.fontWeight)]);
    if (s.letterSpacing) vars.all.push([`${s.name}-letter-spacing`, s.letterSpacing]);
  }
  for (const [name, value] of fixed) vars.all.push([name, value]);
  for (const t of [...tokens.color.tokens, ...tokens.shadow.tokens]) {
    for (const theme of THEMES) vars[theme].push([t.name, t.value[theme]]);
  }
  return vars;
}

const block = (selector, entries, indent = '') =>
  `${indent}${selector} {\n${entries.map(([n, v]) => `${indent}  --sk-${n}: ${v};`).join('\n')}\n${indent}}\n`;

function fontsCss() {
  const faces = tokens.type.fonts.map(
    (f) =>
      `@font-face {\n  font-family: '${f.family}';\n  src: url('./${f.file}') format('woff2');\n  font-weight: ${f.weight};\n  font-style: ${f.style};\n  font-display: swap;\n}\n`,
  );
  return [HEADER, ...faces].join('\n');
}

function tokensCss() {
  const vars = variables();
  const dark = [['color-scheme', 'dark'], ...vars.dark];
  return [
    HEADER,
    block(':root', [...vars.all, ['color-scheme', 'light'], ...vars.light]),
    // --sk-color-scheme is a plain variable; the scope that uses the tokens sets color-scheme from it.
    block(':root[data-theme="dark"]', dark),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme])', dark, '  ')}}\n`,
  ].join('\n');
}

function themeCss() {
  const lines = [];
  for (const t of tokens.color.tokens) lines.push(`--color-sk-${t.name}: var(--sk-${t.name});`);
  for (const family of Object.keys(tokens.type.families)) lines.push(`--font-sk-${family}: var(--sk-font-${family});`);
  for (const s of textStyles) {
    lines.push(
      `--text-sk-${s.name}: var(--sk-${s.name}-size);`,
      `--text-sk-${s.name}--line-height: var(--sk-${s.name}-line-height);`,
      `--text-sk-${s.name}--font-weight: var(--sk-${s.name}-weight);`,
    );
    if (s.letterSpacing) lines.push(`--text-sk-${s.name}--letter-spacing: var(--sk-${s.name}-letter-spacing);`);
  }
  for (const t of tokens.spacing.tokens) lines.push(`--spacing-sk-${t.name.replace('space-', '')}: var(--sk-${t.name});`);
  for (const t of [...tokens.radius.tokens, ...tokens.wobble.tokens]) {
    lines.push(`--radius-sk-${t.name.replace('radius-', '')}: var(--sk-${t.name});`);
  }
  for (const t of tokens.shadow.tokens) lines.push(`--shadow-sk-${t.name.replace('shadow-', '')}: var(--sk-${t.name});`);
  return `${HEADER}@theme inline {\n${lines.map((l) => `  ${l}`).join('\n')}\n}\n`;
}

// WCAG 2.x relative luminance and contrast ratio.
function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const lin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
}
const ratio = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

// Floors from the design-system README: text 4.5:1 on the grounds its token note names; marks (stage
// colours) 3:1; the focus ring at least 4.3:1 on every surface.
const GROUNDS = ['bg', 'surface', 'surface-sunken'];
const PAIRS = [
  ...GROUNDS.map((g) => ['text', g, 4.5]),
  ...GROUNDS.map((g) => ['text-muted', g, 4.5]),
  ['primary', 'bg', 4.5],
  ['primary', 'surface', 4.5],
  ...GROUNDS.map((g) => ['primary', g, 4.3]),
  ['on-primary', 'primary', 4.5],
  ...['success', 'warning', 'danger'].flatMap((c) => [[c, 'bg', 4.5], [c, 'surface', 4.5]]),
  ...tokens.color.tokens
    .filter((t) => t.name.startsWith('stage-'))
    .flatMap((t) => [[t.name, 'bg', 3], [t.name, 'surface', 3]]),
];

function contrastFailures() {
  const color = Object.fromEntries(tokens.color.tokens.map((t) => [t.name, t.value]));
  const failures = [];
  for (const theme of THEMES) {
    for (const [fg, bg, floor] of PAIRS) {
      const r = ratio(color[fg][theme], color[bg][theme]);
      if (r < floor) failures.push(`${theme}: ${fg} on ${bg} is ${r.toFixed(2)}:1, below ${floor}:1`);
    }
  }
  return failures;
}

const outputs = {
  [`${DIR}/tokens.css`]: tokensCss(),
  [`${DIR}/fonts.css`]: fontsCss(),
  [`${DIR}/theme.css`]: themeCss(),
};

if (process.argv.includes('--check')) {
  const problems = [];
  const css = outputs[`${DIR}/tokens.css`];
  const vars = variables();
  for (const [name] of [...vars.all, ...vars.light, ...vars.dark]) {
    if (!css.includes(`--sk-${name}:`)) problems.push(`token ${name} has no CSS variable`);
  }
  for (const [path, expected] of Object.entries(outputs)) {
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      // Reported as stale below.
    }
    if (current !== expected) problems.push(`${path} is stale; run pnpm tokens`);
  }
  problems.push(...contrastFailures());
  if (problems.length) {
    console.error(`sketch-tokens: ${problems.length} problem(s)\n- ${problems.join('\n- ')}`);
    process.exit(1);
  }
  console.log(`sketch-tokens: ${vars.all.length + vars.light.length} variables, ${PAIRS.length * THEMES.length} contrast pairs pass`);
} else {
  for (const [path, content] of Object.entries(outputs)) writeFileSync(path, content);
  console.log(`sketch-tokens: wrote ${Object.keys(outputs).join(', ')}`);
}
