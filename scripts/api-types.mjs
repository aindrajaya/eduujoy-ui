// Generates src/api/schema.d.ts from docs/openapi.json (the committed contract copy).
//   node scripts/api-types.mjs          write the types
//   node scripts/api-types.mjs --check  fail if the committed types are stale (CI)
//   node scripts/api-types.mjs --sync   first copy ../api/openapi.json over docs/openapi.json
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import openapiTS, { astToString } from 'openapi-typescript';

const SPEC = 'docs/openapi.json';
const OUT = 'src/api/schema.d.ts';
const API_SPEC = '../api/openapi.json';
const HEADER = '// Generated by scripts/api-types.mjs from docs/openapi.json. Do not edit.\n\n';

const args = new Set(process.argv.slice(2));

if (args.has('--sync')) {
  if (!existsSync(API_SPEC)) {
    console.error(`${API_SPEC} not found. Run \`pnpm openapi:export\` in api/ first.`);
    process.exit(1);
  }
  copyFileSync(API_SPEC, SPEC);
  console.log(`Copied ${API_SPEC} -> ${SPEC}`);
}

const spec = JSON.parse(readFileSync(SPEC, 'utf8'));
const ast = await openapiTS(spec, { alphabetize: true, exportType: false });
const output = HEADER + astToString(ast);

if (args.has('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== output) {
    console.error(`${OUT} is stale. Run \`pnpm api:types\` and commit the result.`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date.`);
} else {
  writeFileSync(OUT, output);
  console.log(`Wrote ${OUT}`);
}
